//! A count before a mana symbol is that many mana of its type (107.4a, 107.4c, 106.1b): "Add
//! six {G}.", "add eight {C}". The cards the grammar reads this way and the engine runs, on
//! their Oracle text: Castle Garenbrig, Su-Chi Cave Guard.
use crate::support::{Board, T, cite, mana_pool, on};
use game::state::Pool;
use game::{Move, Zone};
use ir::Color;
use ir::mana::ManaSymbol;

/// Castle Garenbrig's last ability: "{2}{G}{G}, {T}: Add six {G}. Spend this mana only to cast
/// creature spells or activate abilities of creatures."
const SIX_GREEN: usize = 2;
const RESTRICTED: &str = "that mana can't be spent on that: its text restricts how it can be spent (106.6)";

/// Player 0 has the Castle's six {G} in their pool, and these other cards.
fn castle(battlefield: &[&str], hand: &[&str], graveyard: &[&str]) -> T {
    let mut t = Board::new(2).battlefield(0, &["Castle Garenbrig"]).battlefield(0, battlefield).hand(0, hand).graveyard(0, graveyard).build();
    t.mana(0, "{G}{G}{G}{G}");
    t.activate(0, "Castle Garenbrig", SIX_GREEN, vec![], mana_pool("GGGG")).unwrap();
    t
}

/// These of the Castle's mana and this ordinary mana, to pay with.
fn paying(t: &T, lots: usize, ordinary: &str) -> Pool {
    let mut pool = mana_pool(ordinary);
    pool.restricted = t.g.players[0].pool.restricted[..lots].to_vec();
    pool
}

#[test]
fn r107_4a_a_counted_symbol_adds_that_many_mana_of_its_type() {
    let t = castle(&[], &[], &[]);
    let pool = &t.g.players[0].pool;
    // restricted mana keeps its type (106.6) and is in the pool as itself
    cite!(["107.4a", "106.1b"]; assert_eq!(pool.restricted.iter().map(|m| m.mana).collect::<Vec<_>>(), vec![ManaSymbol::Color(Color::Green); 6]));
    assert_eq!((pool.colors, pool.colorless), ([0; 5], 0), "the {{2}}{{G}}{{G}} was paid");
    cite!(["605.3b"]; assert!(t.g.stack.is_empty(), "a mana ability resolves as it is activated"));
}

#[test]
fn r106_6_the_castles_mana_is_spent_on_creature_spells_and_abilities_of_creatures_only() {
    // a creature spell, and an ability of a creature on the battlefield
    let mut t = castle(&["Patagia Golem"], &["Llanowar Elves"], &[]);
    let one = paying(&t, 1, "");
    cite!(["106.6"]; ok: t.cast(0, "Llanowar Elves", vec![], one).map(|_| ()));
    let three = paying(&t, 3, "");
    cite!(["106.6"]; ok: t.activate(0, "Patagia Golem", 0, vec![], three).map(|_| ()));
    assert_eq!(t.g.players[0].pool.restricted.len(), 2, "four of the six were spent");

    // not a noncreature spell, nor an ability of a permanent that is no creature
    let mut t = castle(&["Patagia Golem", "Rod of Ruin"], &["Giant Growth"], &[]);
    let one = paying(&t, 1, "");
    cite!(["106.6"]; refused(RESTRICTED): t.cast(0, "Giant Growth", vec![on(0, Zone::Battlefield, "Patagia Golem")], one).map(|_| ()));
    let three = paying(&t, 3, "");
    let golem = t.find("Patagia Golem");
    let rod = t.find("Rod of Ruin");
    let shoot = Move::Activate { source: rod, ability: 0, targets: vec![vec![game::Target::Object(golem)]], paying: vec![] };
    cite!(["106.6"]; refused(RESTRICTED): t.g.act(0, Move::Paying(three, Box::new(shoot))));
    assert_eq!(t.g.players[0].pool.restricted.len(), 6, "nothing was spent");
}

/// Ruling of 2019-10-04: "The mana generated by Castle Garenbrig's last ability can't be spent
/// to activate abilities of creature cards that aren't on the battlefield."
#[test]
fn r106_6_the_castles_mana_does_not_pay_for_an_ability_of_a_creature_card_in_a_graveyard() {
    // Clay Revenant: "{2}{B}: Return this card from your graveyard to your hand."
    let mut t = castle(&[], &[], &["Clay Revenant"]);
    t.mana(0, "{B}{2}");
    let revenant = t.find_in(0, Zone::Graveyard, "Clay Revenant");
    let back = || Move::Activate { source: revenant, ability: 1, targets: vec![], paying: vec![] };
    let with_the_castles = paying(&t, 2, "B");
    cite!(["106.6"]; refused(RESTRICTED): t.g.act(0, Move::Paying(with_the_castles, Box::new(back()))));
    // ordinary mana pays for it
    cite!(["106.6"]; ok: t.g.act(0, Move::Paying(mana_pool("{B}{2}"), Box::new(back()))));
}

#[test]
fn r614_1d_the_castle_enters_tapped_unless_its_controller_controls_a_forest() {
    // "This land enters tapped unless you control a Forest."
    for (lands, tapped) in [(&[][..], true), (&["Forest"][..], false), (&["Island"][..], true)] {
        let mut t = Board::new(2).battlefield(0, lands).hand(0, &["Castle Garenbrig"]).build();
        let card = t.find_in(0, Zone::Hand, "Castle Garenbrig");
        t.g.act(0, Move::PlayLand(card)).unwrap();
        let castle = t.find_in(0, Zone::Battlefield, "Castle Garenbrig");
        cite!(["614.1d"]; case: format!("{lands:?}"); assert_eq!(t.g.obj(castle).tapped, tapped, "{lands:?}"));
    }
    // a Forest an opponent controls is not one you control
    let mut t = Board::new(2).battlefield(1, &["Forest"]).hand(0, &["Castle Garenbrig"]).build();
    let card = t.find_in(0, Zone::Hand, "Castle Garenbrig");
    t.g.act(0, Move::PlayLand(card)).unwrap();
    let castle = t.find_in(0, Zone::Battlefield, "Castle Garenbrig");
    cite!(["614.1d"]; assert!(t.g.obj(castle).tapped));
}

#[test]
fn r107_4a_a_chapter_adds_a_counted_symbol() {
    // The Flux: "VI — Add six {R}." Its sixth lore counter is put on it as its controller's
    // precombat main phase begins (714.3c).
    let mut t = Board::new(2).fill(8).at(ir::Part::Upkeep).battlefield(0, &["The Flux"]).counters("The Flux", "lore", 5).build();
    let flux = t.find("The Flux");
    for _ in 0..10 {
        if t.g.part == ir::Part::PrecombatMain { break; }
        t.pass_all();
    }
    cite!(["714.3c"]; assert_eq!(t.g.obj(flux).counters.get("lore"), Some(&6)));
    cite!(["714.2b"]; assert_eq!(t.g.stack.len(), 1, "chapter VI triggered"));
    t.resolve();
    let pool = &t.g.players[0].pool;
    cite!(["107.4a", "106.1b"]; assert_eq!((pool.colors[Color::Red as usize], pool.total()), (6, 6)));
}

#[test]
fn r107_4c_a_counted_colorless_symbol_from_a_triggered_ability_and_mana_kept_until_end_of_turn() {
    // Su-Chi Cave Guard: "When this creature dies, add eight {C}. Until end of turn, you don't
    // lose this mana as steps and phases end."
    let mut t = Board::new(2).fill(5).battlefield(0, &["Su-Chi Cave Guard"]).hand(0, &["Murder"]).build();
    t.mana(0, "{1}{B}{B}");
    t.cast(0, "Murder", vec![on(0, Zone::Battlefield, "Su-Chi Cave Guard")], mana_pool("{1}{B}{B}")).unwrap();
    let colorless = |t: &T| {
        let pool = &t.g.players[0].pool;
        pool.colorless + pool.restricted.iter().filter(|m| m.mana == ManaSymbol::Colorless).count() as u32
    };
    // Murder resolves and the Guard dies. Its ability triggers from dying, not from mana
    // being added, so it is no mana ability: it goes on the stack and adds nothing yet
    t.pass_all();
    cite!(["605.5a", "603.6c"]; assert_eq!((t.g.stack.len(), colorless(&t)), (1, 0)));
    t.resolve();
    cite!(["107.4c", "603.6c"]; assert_eq!(colorless(&t), 8, "the dies trigger resolved and added eight {{C}}"));
    assert_eq!(t.g.players[0].pool.total(), 8);
    // the pool empties as each step and phase ends (106.4); this mana stays for the turn
    let (turn, part) = (t.g.turn, t.g.part);
    t.pass_all();
    assert!(t.g.turn == turn && t.g.part != part, "the step ended within the turn");
    cite!(["106.4"]; assert_eq!(colorless(&t), 8));
    // and is lost once the turn has ended
    for _ in 0..40 {
        if t.g.turn != turn { break; }
        t.pass_all();
    }
    assert_ne!(t.g.turn, turn, "the next turn began");
    cite!(["106.4"]; assert_eq!(t.g.players[0].pool.total(), 0));
}
