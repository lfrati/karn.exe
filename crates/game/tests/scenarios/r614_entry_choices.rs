/// `n` cards went from graveyards to the battlefield, and nothing but their arrivals happened
/// between the first and the last: they entered at once, after every choice was collected.
/// (Which log stretch is one event is not public; this is the observable part of it.)
fn arrived_together(g: &Game, n: usize) {
    let arrivals: Vec<usize> = g.log.iter().enumerate()
        .filter(|(_, e)| matches!(e, Event::ZoneChanged { from: Zone::Graveyard, to: Zone::Battlefield, .. }))
        .map(|(i, _)| i).collect();
    assert_eq!(arrivals.len(), n);
    let between = &g.log[arrivals[0]..=arrivals[n - 1]];
    assert!(between.iter().all(|e| matches!(e, Event::Moved { to: Zone::Battlefield, .. } | Event::ZoneChanged { to: Zone::Battlefield, .. })),
        "something happened between the arrivals: {between:?}");
}

#[test]
fn r101_4_open_the_vaults_asks_entry_choices_in_apnap_order_from_a_nonzero_active_player() {
    let mut g = game(4, &[SHARED_TRIUMPH, PRISM_RING, OPEN_THE_VAULTS, PLAINS, RAIDERS, BEARS]);
    for player in 0..4 {
        for _ in 0..5 {
            g.put(player, PLAINS, Zone::Library);
        }
    }
    // play on to the third turn: player 2's (101.4 starts from the active player)
    for _ in 0..200 {
        if g.active == 2 && g.part == ir::Part::PrecombatMain {
            break;
        }
        assert_eq!(g.decision, None, "nothing to decide on the way: {:?}", g.decision);
        g.act(g.priority, Move::Pass).unwrap();
    }
    assert_eq!((g.turn, g.active, g.part, g.priority), (3, 2, ir::Part::PrecombatMain, 2));
    // every player owns what is in their graveyard; player 2 must make two choices, player 1
    // none (a creature card is not returned)
    let triumph0 = g.put(0, SHARED_TRIUMPH, Zone::Graveyard);
    let bears1 = g.put(1, BEARS, Zone::Graveyard);
    let ring2 = g.put(2, PRISM_RING, Zone::Graveyard);
    let triumph2 = g.put(2, SHARED_TRIUMPH, Zone::Graveyard);
    let ring3 = g.put(3, PRISM_RING, Zone::Graveyard);
    let returning = [triumph0, ring2, triumph2, ring3];
    let goblin = g.put(1, RAIDERS, Zone::Battlefield);
    let bear = g.put(3, BEARS, Zone::Battlefield);
    mana(&mut g, 2, &[W, W, W, W, W, W]);
    let vaults = cast(&mut g, 2, OPEN_THE_VAULTS, vec![], "WWWWWW");
    pass_all(&mut g);
    // each player's answer to each kind of choice
    let answer = |player: PlayerId, kind: Kind| match (player, kind) {
        (2, Kind::Color) => Value::Color(Color::Red),
        (2, Kind::CreatureType) => creature_type("Goblin"),
        (3, Kind::Color) => Value::Color(Color::Blue),
        (0, Kind::CreatureType) => creature_type("Bear"),
        other => panic!("{other:?} was not to be asked"),
    };
    let mut asked: Vec<(PlayerId, Kind)> = Vec::new();
    let mut observed = Vec::new();
    while let Some(Decision::Choose { player, choice: Choice::Value(kind) }) = g.decision.clone() {
        waits_for_entry_choice(&mut g, vaults, player, kind);
        for card in returning {
            assert_eq!(g.obj(card).zone, Zone::Graveyard, "nothing enters before all choices are made");
        }
        assert!(g.battlefield.iter().all(|o| !returning.iter().any(|r| g.obj(*r).chars.name == g.obj(*o).chars.name)));
        cite!(["101.4b"]; assert_eq!(g.public_choices().cloned().collect::<Vec<_>>(), observed,
            "101.4b: later choosers can see earlier public answers, once each"));
        let card = g.entering_card().expect("the decision identifies the entering card");
        assert!(returning.contains(&card));
        assert_eq!(g.obj(card).owner, player);
        asked.push((player, kind));
        let reply = Answer::Value(answer(player, kind));
        observed.push(game::state::PublicChoice::Entry { player, card, answer: reply.clone() });
        g.act(player, Move::Choose(reply)).unwrap();
    }
    assert_eq!(g.decision, None, "only value choices were asked");
    assert_eq!(g.entering_card(), None);
    assert_eq!(g.public_choices().count(), 0, "the completed collection no longer exposes pending answers");
    // APNAP from player 2: 2 (twice, in the order they choose, 101.4c), then 3, then 0
    cite!(["101.4c"]; assert_eq!(asked.iter().map(|(p, _)| *p).collect::<Vec<_>>(), [2, 2, 3, 0]));
    let mut kinds2: Vec<String> = asked[..2].iter().map(|(_, k)| format!("{k:?}")).collect();
    kinds2.sort();
    assert_eq!(kinds2, ["Color", "CreatureType"]);
    assert!(g.log.contains(&Event::Resolved { spell: vaults }));
    // they entered at once, each under its owner's control with its owner's choice
    arrived_together(&g, 4);
    let mut entered: Vec<(PlayerId, String, PlayerId, Value)> = g.battlefield.iter()
        .filter(|o| ["Shared Triumph", "Prism Ring"].contains(&g.obj(**o).chars.name.as_str()))
        .map(|o| {
            let (chooser, value) = chosen(&g, *o);
            (g.obj(*o).controller, g.obj(*o).chars.name.clone(), chooser, value)
        })
        .collect();
    entered.sort_by_key(|e| format!("{e:?}"));
    assert_eq!(entered, [
        (0, "Shared Triumph".to_string(), 0, creature_type("Bear")),
        (2, "Prism Ring".to_string(), 2, Value::Color(Color::Red)),
        (2, "Shared Triumph".to_string(), 2, creature_type("Goblin")),
        (3, "Prism Ring".to_string(), 3, Value::Color(Color::Blue)),
    ]);
    for (owner, card) in [(0, triumph0), (2, ring2), (2, triumph2), (3, ring3)] {
        assert_eq!(g.obj(card).owner, owner);
    }
    assert_eq!(names(&g, &g.players[1].graveyard), ["Grizzly Bears"]);
    assert_eq!(g.players[1].graveyard, vec![bears1]);
    // player 0's Bear and player 2's Goblin choices both apply to every player's creatures
    assert_eq!((g.power(goblin), g.power(bear)), (Some(2), Some(3)));
}


