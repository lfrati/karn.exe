//! Choices made as a nonland permanent enters (614.1c, 614.12a), when it is a permanent spell
//! that resolves (608.3a). Every card is read from its printed (Oracle) text.
//!
//! 614.1c: "Effects that read “[This permanent] enters with . . . ,” “As [this permanent]
//! enters . . . ,” or “[This permanent] enters as . . . “ are replacement effects."
//! 614.12a: "If a replacement effect that modifies how a permanent enters the battlefield
//! requires a choice, that choice is made before the permanent enters the battlefield."
//! 608.3a: "If the object that’s resolving has no targets, it becomes a permanent and enters
//! the battlefield under the control of the spell’s controller."
//! 607.2d: an ability that refers to "the chosen [value]" is linked to the ability that made
//! the choice and "refers only to a choice made as a result of the first ability."
//! 611.3a: "A continuous effect generated by a static ability isn’t “locked in”; it applies at
//! any given moment to whatever its text indicates."
//! 701.6a: "To counter a spell or ability means to cancel it, removing it from the stack. It
//! doesn’t resolve and none of its effects occur. A countered spell is put into its owner’s
//! graveyard."
//!
//! Entry capability and each witness's readers must be admitted and exercised together.

