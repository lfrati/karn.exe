/// The player casts this card from their hand; the spell on the stack.
fn cast(g: &mut Game, player: PlayerId, def: usize, targets: Vec<Vec<Target>>, spending: &str) -> ObjId {
    let card = g.put(player, def, Zone::Hand);
    g.act(player, paid(spending, Move::Cast { card, targets })).unwrap_or_else(|e| panic!("cast {}: {e}", g.defs[def].name()));
    g.log.iter().rev().find_map(|event| match event {
        Event::Cast { spell, by } if *by == player => Some(*spell),
        _ => None,
    }).expect("the cast event identifies the spell, even when a trigger is above it")
}

/// Every player passes in succession, from whoever has priority (405.5).
fn pass_all(g: &mut Game) {
    for _ in 0..g.players.len() {
        let p = g.priority;
        g.act(p, Move::Pass).unwrap_or_else(|e| panic!("player {p} passes: {e}"));
    }
}

/// The permanent on the battlefield with this name, if exactly one.
fn named(g: &Game, name: &str) -> Option<ObjId> {
    let all: Vec<ObjId> = g.battlefield.iter().copied().filter(|o| g.obj(*o).chars.name == name).collect();
    match all[..] {
        [one] => Some(one),
        [] => None,
        _ => panic!("more than one {name}"),
    }
}

/// What a permanent chose as it entered (607.2d): its one choice record.
fn chosen(g: &Game, permanent: ObjId) -> (PlayerId, Value) {
    let [record] = &g.obj(permanent).choices[..] else {
        panic!("{} has {} choice records", g.obj(permanent).chars.name, g.obj(permanent).choices.len())
    };
    (record.chooser, record.value.clone())
}

/// 614.12a: the spell waits, on the stack and unresolved, for `chooser` to choose a value of
/// this kind; meanwhile no player can do anything else, passing included, and a rejected move
/// leaves the game as it was.
fn waits_for_entry_choice(g: &mut Game, spell: ObjId, chooser: PlayerId, kind: Kind) {
    assert_eq!(g.decision, Some(Decision::Choose { player: chooser, choice: Choice::Value(kind) }));
    let Some((who, Asked::Value { kind: asked, options })) = g.asked() else { panic!("no value asked: {:?}", g.asked()) };
    assert_eq!((who, asked), (chooser, kind));
    assert_eq!(options, game::binding::options(kind), "the whole rules-defined domain (105.1, 205.3m)");
    assert!(g.entering_card().is_some(), "the entry question must identify its object");
    cite!(["614.12a"]; assert_eq!(g.obj(spell).zone, Zone::Stack, "the spell has not finished resolving"));
    assert_eq!(g.stack.last(), Some(&spell));
    assert!(!g.log.contains(&Event::Resolved { spell }));
    let before = format!("{g:?}");
    for p in 0..g.players.len() {
        crate::support::refused(g.act(p, Move::Pass), "a decision is pending: a choice of how the permanent enters the battlefield (614.12)");
        assert_eq!(format!("{g:?}"), before, "a rejected pass by player {p} changed the game");
    }
}

/// The permanent spell `spell` became the permanent `name` once the choice was made (608.3a).
fn entered(g: &Game, spell: ObjId, name: &str) -> ObjId {
    let permanent = named(g, name).unwrap_or_else(|| panic!("{name} is not on the battlefield"));
    assert!(g.log.contains(&Event::Resolved { spell }));
    assert!(!g.stack.contains(&spell));
    cite!(["608.3a"]; assert!(g.log.iter().any(|e| matches!(e, Event::ZoneChanged { was, now: Some(now), from: Zone::Stack, to: Zone::Battlefield }
        if *was == spell && *now == permanent))));
    permanent
}

