#[test]
fn r603_6a_brass_herald_chooses_before_entering_then_its_enters_ability_and_static_read_that_type() {
    let mut g = game(2, &[BRASS_HERALD, RAIDERS, PIKER, BEARS, PLAINS]);
    // the library, bottom first: the fifth card from the top is a Goblin that is not revealed
    for card in [PLAINS, PIKER, RAIDERS, BEARS, PIKER, RAIDERS] {
        g.put(0, card, Zone::Library);
    }
    let top_four = g.top_cards(0, 4);
    let theirs = g.put(1, RAIDERS, Zone::Battlefield);
    let bear = g.put(1, BEARS, Zone::Battlefield);
    mana(&mut g, 0, &[C, C, C, C, C, C]);
    let spell = cast(&mut g, 0, BRASS_HERALD, vec![], "CCCCCC");
    let log = g.log.len();
    pass_all(&mut g);
    waits_for_entry_choice(&mut g, spell, 0, Kind::CreatureType);
    cite!(["614.12a"]; assert_eq!(named(&g, "Brass Herald"), None));
    assert_eq!(g.stack, vec![spell], "its enters ability has not triggered");
    assert!(!g.log[log..].iter().any(|e| matches!(e, Event::Revealed { .. })));
    g.act(0, Move::Choose(Answer::Value(creature_type("Goblin")))).unwrap();
    let herald = entered(&g, spell, "Brass Herald");
    assert_eq!(chosen(&g, herald), (0, creature_type("Goblin")));
    // "Creatures of the chosen type get +1/+1.": the opponent's Goblin, not their Bear, and
    // not the Herald itself, a Golem
    assert_eq!((g.power(theirs), g.toughness(theirs)), (Some(2), Some(2)));
    assert_eq!((g.power(bear), g.power(herald)), (Some(2), Some(2)));
    // its enters ability triggered as it entered, and resolves now
    cite!(["603.6a"]; assert_eq!(g.stack.len(), 1));
    assert_eq!(g.obj(g.stack[0]).controller, 0);
    assert!(g.players[0].hand.is_empty());
    pass_all(&mut g);
    assert!(g.stack.is_empty());
    let revealed: Vec<Vec<ObjId>> = g.log[log..].iter().filter_map(|e| match e {
        Event::Revealed { player: 0, cards } => Some(cards.clone()),
        _ => None,
    }).collect();
    let [cards] = &revealed[..] else { panic!("one reveal expected: {revealed:?}") };
    let (mut cards, mut top_four) = (cards.clone(), top_four);
    cards.sort();
    top_four.sort();
    assert_eq!(cards, top_four, "the top four cards, revealed (701.20a)");
    let mut hand = names(&g, &g.players[0].hand);
    hand.sort();
    cite!(["607.2d"]; assert_eq!(hand, ["Goblin Piker", "Mons's Goblin Raiders", "Mons's Goblin Raiders"], "the creature cards of the chosen type"));
    assert_eq!(names(&g, &g.players[0].library), ["Grizzly Bears", "Plains", "Goblin Piker"], "the rest on the bottom; the fifth card stays");
    assert_eq!(g.decision, None);
}

