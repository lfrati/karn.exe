    assert_eq!((g.power(goblin), g.power(bear)), (Some(2), Some(3)));
    // Prism Ring is an artifact, not an enchantment card: it stays
    assert_eq!(names(&g, &g.players[0].graveyard), ["Prism Ring", "Replenish"]);
    assert!(g.players[0].graveyard.contains(&ring), "the artifact never moved");
    arrived_together(&g, 2);
