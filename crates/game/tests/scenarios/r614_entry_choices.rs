// Entering again, and entering by an instruction rather than by resolving as a spell.
//
// 400.7: "An object that moves from one zone to another becomes a new object with no memory
// of, or relation to, its previous existence."
// 603.6d: "As [this permanent] enters . . ." text "is a static ability—not a triggered
// ability—whose effect occurs as part of the event that puts the permanent onto the
// battlefield."
// 603.6a: "Enters-the-battlefield abilities trigger when a permanent enters the battlefield."
// 401.4: "If an effect puts two or more cards in a specific position in a library at the same
// time, the owner of those cards may arrange them in any order."
// 101.4: "If multiple players would make choices and/or take actions at the same time, the
// active player [...] makes any choices required, then the next player in turn order [...],
// followed by the remaining nonactive players in turn order. Then the actions happen
// simultaneously."
// 101.4b: "A player knows the choices made by the previous players when making their choice"
// 101.4c: "If a player would make more than one choice at the same time, the player makes the
// choices in the order specified. If no order is specified, the player chooses the order."

/// The names of these objects, in order.
fn names(g: &Game, objects: &[ObjId]) -> Vec<String> {
    objects.iter().map(|o| g.obj(*o).chars.name.clone()).collect()
}

/// Cast Brass Herald, choose this creature type for it, and resolve its enters ability.
fn herald(g: &mut Game, ty: &str) -> ObjId {
    mana(g, 0, &[C, C, C, C, C, C]);
    let spell = cast(g, 0, BRASS_HERALD, vec![], "CCCCCC");
    pass_all(g);
    waits_for_entry_choice(g, spell, 0, Kind::CreatureType);
    g.act(0, Move::Choose(Answer::Value(creature_type(ty)))).unwrap();
    let herald = entered(g, spell, "Brass Herald");
    pass_all(g);
    assert!(g.stack.is_empty());
    herald
}

