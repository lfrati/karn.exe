    let mut answers = vec![creature_type("Bear"), creature_type("Goblin")];
    while g.decision.is_some() {
        waits_for_entry_choice(&mut g, replenish, 0, Kind::CreatureType);
        cite!(["614.12a"]; assert_eq!(named(&g, "Shared Triumph"), None, "neither enters before every choice is made"));
        assert_eq!(g.players[0].graveyard, vec![first, second, ring]);
        let value = answers.pop().expect("one choice for each Shared Triumph, no more");
        g.act(0, Move::Choose(Answer::Value(value))).unwrap();
    }
    assert!(answers.is_empty(), "one choice for each Shared Triumph");
    assert!(g.log.contains(&Event::Resolved { spell: replenish }));
    let triumphs: Vec<ObjId> = g.battlefield.iter().copied().filter(|o| g.obj(*o).chars.name == "Shared Triumph").collect();
    assert_eq!(triumphs.len(), 2);
    let mut values: Vec<Value> = triumphs.iter().map(|t| chosen(&g, *t).1).collect();
    values.sort_by_key(|v| format!("{v:?}"));
